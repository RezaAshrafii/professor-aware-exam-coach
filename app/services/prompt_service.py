def _structured_output_instruction(mode: str) -> str:
    response_model = structured_model_for_mode(mode)
    if response_model is None:
        return ""

    schema = json.dumps(response_model.model_json_schema(), ensure_ascii=False, indent=2)
    return f"""
قرارداد خروجی اجباری:
- فقط و فقط یک JSON معتبر برگردان؛ هیچ Markdown، code fence، توضیح قبل یا بعد از JSON ننویس.
- JSON باید با schema زیر منطبق باشد.
- همه فیلدهای اجباری را پر کن. برای داده ناموجود از آرایه خالی، null یا claim با status=unknown مطابق schema استفاده کن؛ داده جعل نکن.
- evidence_refs فقط می‌تواند به منابعی اشاره کند که در بخش «منابع بازیابی‌شده» آمده‌اند.
- در هر evidence_ref، source_number، filename و chunk_index باید دقیقاً با همان منبع بازیابی‌شده یکسان باشند.
- اگر شاهدی وجود ندارد، evidence_refs را خالی بگذار؛ شماره یا نام فایل را حدس نزن.
- متن support باید بازگویی کوتاه شاهد باشد، نه نقل‌قول ساختگی.
- اعداد confidence بین 0 و 1 هستند.

JSON Schema ({response_model.__name__}):
{schema}
""".strip()


def build_prompt(
    course: dict[str, Any],
    mode: str,
    user_input: str,
    evidence: list[dict[str, Any]],
) -> tuple[str, str]:
    mode_instruction = MODE_INSTRUCTIONS.get(mode, MODE_INSTRUCTIONS["teach"])
    course_context = f"""
اطلاعات درس:
- نام درس: {course.get('name', '')}
- استاد: {course.get('professor', '') or 'نامشخص'}
- ترم: {course.get('term', '') or 'نامشخص'}
- تاریخ امتحان: {course.get('exam_date', '') or 'نامشخص'}
- نمره هدف: {course.get('target_grade') if course.get('target_grade') is not None else 'نامشخص'}
- زمان روزانه: {course.get('daily_minutes', 90)} دقیقه
- محدوده امتحان: {course.get('exam_scope', '') or 'نامشخص'}
- یادداشت دانشجو: {course.get('notes', '') or 'ندارد'}
""".strip()

    evidence_text = "\n\n".join(
        (
            f"[منبع {index} | نوع: {item.get('evidence_kind', 'source_chunk')} | "
            f"فایل: {item.get('filename', 'نامشخص')} | قطعه: {item.get('chunk_index', '?')}]\n"
            f"{item['content']}"
        )
        for index, item in enumerate(evidence, start=1)
    ) or "هیچ منبع بازیابی‌شده‌ای وجود ندارد. از دانش عمومی استفاده کن و عدم‌قطعیت را اعلام کن."

    structured_instruction = _structured_output_instruction(mode)
    instruction_parts = [
        BASE_INSTRUCTIONS,
        f"حالت جاری: {MODE_LABELS.get(mode, mode)}\n{mode_instruction}",
    ]
    if structured_instruction:
        instruction_parts.append(structured_instruction)

    instructions = "\n\n".join(instruction_parts)
    input_text = f"{course_context}\n\nمنابع بازیابی‌شده:\n{evidence_text}\n\nدرخواست دانشجو:\n{user_input}"
    return instructions, input_text
